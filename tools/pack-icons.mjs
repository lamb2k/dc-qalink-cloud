  'diff', 'pipette', 'layers', 'list', 'panel-left', 'sun', 'moon', 'bell', 'user', 'loader-circle', 'hand', 'move',
  'timer', 'gauge', 'box', 'monitor', 'gamepad-2', 'git-commit-horizontal', 'file-up', 'circle-check', 'circle-x',
  'circle-dot', 'circle', 'menu', 'square-split-horizontal', 'square-split-vertical', 'image', 'ruler', 'plus', 'house',
