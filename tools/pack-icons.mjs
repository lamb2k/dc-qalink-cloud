const out = {}; const missing = [];
for (const n of [...new Set(names)]) {
  const p = root + `node_modules/lucide-static/icons/${n}.svg`;
  if (!existsSync(p)) { missing.push(n); continue; }
  const s = readFileSync(p, 'utf8');
  out[n] = s.slice(s.indexOf('>', s.indexOf('<svg')) + 1, s.lastIndexOf('</svg>')).replace(/<!--.*?-->/g, '').replace(/\s+/g, ' ').trim();
}
writeFileSync(root + 'src/ui/icons-data.ts', `// Generated by tools/pack-icons.mjs from lucide-static (ISC licence, see LICENSE-lucide.txt). Do not edit.
export const ICONS: Record<string, string> = ${JSON.stringify(out, null, 0)};
`);
console.log('icons', Object.keys(out).length, 'missing', missing.join(',') || 'none');
