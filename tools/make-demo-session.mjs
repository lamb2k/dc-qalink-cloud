// ---------------------------------------------------------------- generated test picture
function testPicture(n, cubes) {
  const W = 640, H = 480, px = Buffer.alloc(W * H * 3);
  const set = (x, y, c) => { if (x < 0 || y < 0 || x >= W || y >= H) return; const i = (y * W + x) * 3; px[i] = c[0]; px[i + 1] = c[1]; px[i + 2] = c[2]; };
  // background: vertical gradient and a floor grid
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const t = y / H; const c = [18 + t * 20, 22 + t * 26, 34 + t * 40];
    if (y > 300) { const gz = 1 / ((y - 290) / 190); const gx = (x - 320) * gz / 40; if (Math.abs(gx - Math.round(gx)) < 0.03 * gz || Math.abs(gz * 4 - Math.round(gz * 4)) < 0.05) { c[0] += 40; c[1] += 46; c[2] += 60; } }
    set(x, y, c.map((v) => Math.min(255, v | 0)));
  }
  // cubes: rotated squares with a lit face and a side, in a ring
  const k = Math.min(16, Math.round(cubes / 6));
  const pal = [[230, 159, 0], [86, 180, 233], [0, 158, 115], [240, 228, 66], [0, 114, 178], [213, 94, 0], [204, 121, 167]];
  for (let i = 0; i < k; i++) {
    const a = (i / k) * Math.PI * 2 + n * 0.02; const cx = 320 + Math.cos(a) * 200, cy = 240 + Math.sin(a) * 70; const s = 22 + 14 * (Math.sin(a) + 1);
    const rot = n * 0.05 + i; const col = pal[i % pal.length];
    quad(cx, cy + s * 0.35, s, rot, col.map((v) => v * 0.55 | 0));
    quad(cx, cy, s, rot, col);
  }
  // colour bars and a picture counter in binary blocks along the bottom
  const bars = [[192, 192, 192], [192, 192, 0], [0, 192, 192], [0, 192, 0], [192, 0, 192], [192, 0, 0], [0, 0, 192]];
  for (let y = 440; y < 464; y++) for (let x = 16; x < 16 + 7 * 40; x++) set(x, y, bars[((x - 16) / 40) | 0]);
  for (let b = 0; b < 12; b++) { const on = (n >> (11 - b)) & 1; for (let y = 440; y < 464; y++) for (let x = 340 + b * 22; x < 340 + b * 22 + 18; x++) set(x, y, on ? [235, 235, 235] : [50, 54, 60]); }
  return png(W, H, px);

  function quad(cx, cy, s, rot, col) {
    const P = [0, 1, 2, 3].map((j) => [cx + Math.cos(rot + j * Math.PI / 2) * s, cy + Math.sin(rot + j * Math.PI / 2) * s * 0.6]);
    const x0 = Math.floor(Math.min(...P.map((p) => p[0]))), x1 = Math.ceil(Math.max(...P.map((p) => p[0])));
    const y0 = Math.floor(Math.min(...P.map((p) => p[1]))), y1 = Math.ceil(Math.max(...P.map((p) => p[1])));
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) {
      let inside = true;
      for (let j = 0; j < 4; j++) { const [ax, ay] = P[j], [bx, by] = P[(j + 1) % 4]; if ((bx - ax) * (y - ay) - (by - ay) * (x - ax) < 0) { inside = false; break; } }
      if (inside) set(x, y, col);
    }
  }
}

function png(w, h, rgb) {
  const raw = Buffer.alloc((w * 3 + 1) * h);
  for (let y = 0; y < h; y++) { raw[y * (w * 3 + 1)] = 0; rgb.copy(raw, y * (w * 3 + 1) + 1, y * w * 3, (y + 1) * w * 3); }
  const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td)); return Buffer.concat([len, td, crc]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 2; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
function crc32(buf) {
  let c, crc = 0xffffffff;
  for (let n = 0; n < buf.length; n++) { c = (crc ^ buf[n]) & 0xff; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crc = (crc >>> 8) ^ c; }
  return (crc ^ 0xffffffff) >>> 0;
}
